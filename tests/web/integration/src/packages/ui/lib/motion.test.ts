import { describe, expect, test } from "vitest";
import { SPRING_DURATIONS, controlSwapMotion, springTransition } from "@kyomi/ui/lib/motion";

const HIDDEN = { opacity: 0, scale: 0.96, filter: "blur(4px)" };
const SHOWN = { opacity: 1, scale: 1, filter: "blur(0px)" };

describe("springTransition", () => {
  test("returns a bounce-free spring for each named duration", () => {
    expect(springTransition("quick")).toEqual({ type: "spring", duration: 0.24, bounce: 0 });
    expect(springTransition("standard")).toEqual({ type: "spring", duration: 0.28, bounce: 0 });
    expect(springTransition("emphasized")).toEqual({ type: "spring", duration: 0.3, bounce: 0 });
    expect(springTransition()).toEqual({
      type: "spring",
      duration: SPRING_DURATIONS.standard,
      bounce: 0,
    });
  });

  test("changes instantly when the user prefers reduced motion", () => {
    expect(springTransition("emphasized", true)).toEqual({ duration: 0 });
  });
});

// Generated by the /ship test coverage audit (Claude).
// Value: protects=controlSwapMotion gives swapped controls one enter/exit recipe and no movement under reduced motion;
//   fails_when=the reduced-motion branch is dropped or the enter and exit states diverge;
//   why_new=motion.test.ts covered only springTransition and no caller asserts on swap motion;
//   seam=none; no_claim=how Motion renders these states in a browser (pure function only).
describe("controlSwapMotion", () => {
  test("enters from and exits to the same slightly scaled, blurred state", () => {
    const motion = controlSwapMotion(false);

    expect(motion).toEqual({ initial: HIDDEN, animate: SHOWN, exit: HIDDEN });
    expect(controlSwapMotion()).toEqual(motion);
  });

  test("applies no enter or exit movement under reduced motion", () => {
    const motion = controlSwapMotion(true);

    expect(motion.initial).toBe(false);
    expect(motion.exit).toBeUndefined();
    expect(motion.animate).toEqual(SHOWN);
  });

  test("keeps the movement while the reduced-motion preference is still unknown", () => {
    expect(controlSwapMotion(null).initial).toEqual(HIDDEN);
  });
});
