import { fireEvent, render, screen } from "@testing-library/react";
import { describe, expect, test, vi } from "vitest";
import { Toolbar } from "@modules/reader/components/toolbar";
import type { ToolbarProps } from "@modules/reader/lib/toolbar";

vi.mock("@kyomi/ui/hooks/use-media-query", () => ({
  useMediaQuery: () => false,
}));

function toolbarProps(overrides: Partial<ToolbarProps> = {}): ToolbarProps {
  return {
    activeMode: "extracted",
    canDecreaseFont: true,
    canIncreaseFont: true,
    contentWidth: "wide",
    extractedAvailable: true,
    fontSizePx: 17,
    isSaved: false,
    onCycleContentWidth: vi.fn(),
    onDecreaseFontSize: vi.fn(),
    onIncreaseFontSize: vi.fn(),
    onOpenOriginal: vi.fn(),
    onShareArticle: vi.fn(),
    onToggleMode: vi.fn(),
    onToggleSaved: vi.fn(),
    onTranslateArticle: vi.fn(),
    ...overrides,
  };
}

describe("reader toolbar", () => {
  test("passes the tooltip side through to read later toasts", () => {
    const onToggleSaved = vi.fn();
    render(
      <Toolbar
        {...toolbarProps({
          onToggleSaved,
          readerFocusMode: true,
          tooltipSide: "bottom",
        })}
      />,
    );

    const button = screen.getByRole("button", { name: "Read later" });
    fireEvent.click(button);

    expect(onToggleSaved).toHaveBeenCalledWith({
      anchor: button,
      side: "bottom",
      sideOffset: 8,
    });
  });

  test("uses the inbox toolbar icon scale for large reader controls", () => {
    render(
      <Toolbar
        {...toolbarProps({
          controlSize: "large",
          readerFocusMode: true,
        })}
      />,
    );

    const button = screen.getByRole("button", { name: "Read later" });
    expect(button.className).toContain("[&_svg]:size-5!");
  });

  test("drops the distill action and shows share without a separator in focus mode", () => {
    render(<Toolbar {...toolbarProps({ readerFocusMode: true })} />);

    expect(screen.queryByRole("button", { name: "Distill this article" })).toBeNull();
    expect(screen.getByRole("button", { name: "Share article" })).toBeTruthy();
    expect(screen.queryByRole("separator")).toBeNull();
  });

  // Generated by the /ship test coverage audit (Claude).
  // Value: protects=toolbar actions per mode: Open source after a separator outside focus, no Distill/Share there, Share reachable in focus mode;
  //   fails_when=Distill returns, Share leaks into the inline toolbar or compact mode, or Share stops calling onShareArticle;
  //   why_new=existing toolbar tests render focus mode only, so the inline and compact layouts changed by this diff had no test;
  //   seam=none; no_claim=motion, tooltips and layout widths (jsdom without CSS).
  test("keeps only Open source after a separator in the inline toolbar", () => {
    render(<Toolbar {...toolbarProps()} />);

    expect(screen.queryByRole("button", { name: "Distill this article" })).toBeNull();
    expect(screen.queryByRole("button", { name: "Share article" })).toBeNull();
    expect(screen.queryByRole("button", { name: "Translate article" })).toBeNull();

    const separator = screen.getByRole("separator");
    const openSource = screen.getByRole("button", { name: "Open source" });
    expect(
      separator.compareDocumentPosition(openSource) & Node.DOCUMENT_POSITION_FOLLOWING,
    ).toBeTruthy();
  });

  test("hides translate and share in the compact focus toolbar", () => {
    render(<Toolbar {...toolbarProps({ readerFocusMode: true, readerFocusVariant: "compact" })} />);

    expect(screen.getByRole("button", { name: "Read later" })).toBeTruthy();
    expect(screen.getByRole("button", { name: "Open source" })).toBeTruthy();
    expect(screen.queryByRole("button", { name: "Translate article" })).toBeNull();
    expect(screen.queryByRole("button", { name: "Share article" })).toBeNull();
    expect(screen.queryByRole("separator")).toBeNull();
  });

  test("shares the article from the focus toolbar", () => {
    const onShareArticle = vi.fn();
    render(<Toolbar {...toolbarProps({ onShareArticle, readerFocusMode: true })} />);

    fireEvent.click(screen.getByRole("button", { name: "Share article" }));

    expect(onShareArticle).toHaveBeenCalledOnce();
  });
});
