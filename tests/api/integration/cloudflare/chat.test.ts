import { afterEach, beforeEach, describe, expect, spyOn, test } from "bun:test";
import worker from "../../../../apps/embeddings/src/index";

const TOKEN = "test-embeddings-token";
const CHAT_URL = "https://embeddings.test/chat";
const MODEL = "@cf/openai/gpt-oss-120b";

/** Workers AI stand-in that records each call and answers with a fixed result or error. */
function fakeAi(result: unknown | (() => never)) {
  const calls: Array<{ model: string; input: Record<string, unknown> }> = [];
  return {
    calls,
    async run(model: string, input: Record<string, unknown>) {
      calls.push({ model, input });
      return typeof result === "function" ? (result as () => never)() : result;
    },
  };
}

function chatRequest(body: unknown, authorization: string | null = `Bearer ${TOKEN}`): Request {
  const headers = new Headers({ "Content-Type": "application/json" });
  if (authorization !== null) {
    headers.set("Authorization", authorization);
  }
  return new Request(CHAT_URL, { method: "POST", headers, body: JSON.stringify(body) });
}

const validBody = {
  model: MODEL,
  messages: [
    { role: "system", content: "Translate into German." },
    { role: "user", content: "<p>Hello</p>" },
  ],
  max_tokens: 1024,
};

let consoleError: ReturnType<typeof spyOn>;

beforeEach(() => {
  consoleError = spyOn(console, "error").mockImplementation(() => {});
});

afterEach(() => {
  consoleError.mockRestore();
});

describe("chat route auth and validation", () => {
  test("rejects a missing or wrong bearer token without calling Workers AI", async () => {
    const ai = fakeAi({ response: "x" });

    for (const authorization of [null, "Bearer wrong"]) {
      const response = await worker.fetch(chatRequest(validBody, authorization), {
        AI: ai,
        EMBEDDINGS_TOKEN: TOKEN,
      });
      expect(response.status).toBe(401);
    }
    expect(ai.calls).toHaveLength(0);
  });

  // Generated by /ship coverage audit
  // Value: protects=/chat refuses oversized or mistyped bodies before spending Workers AI tokens on them;
  //   fails_when=the 400000-char total cap, integer max_tokens, string reasoning_effort, object response_format or JSON-object body check loosens;
  //   why_new=the table covered model, range, empty and bad-role bodies only, not the total-size cap or these type checks;
  //   seam=none;
  //   no_claim=green does not prove the Worker rejects every body a real Workers AI model would refuse.
  test("rejects unlisted models, invalid fields and oversized input without calling Workers AI", async () => {
    const ai = fakeAi({ response: "x" });
    const env = { AI: ai, EMBEDDINGS_TOKEN: TOKEN };

    for (const body of [
      { ...validBody, model: "@cf/meta/llama-3.1-8b-instruct" },
      { ...validBody, max_tokens: 0 },
      { ...validBody, max_tokens: 1_000_000 },
      { ...validBody, max_tokens: 1.5 },
      { ...validBody, messages: [] },
      { ...validBody, messages: [{ role: "tool", content: "x" }] },
      {
        ...validBody,
        messages: [
          { role: "system", content: "x".repeat(200_001) },
          { role: "user", content: "y".repeat(200_000) },
        ],
      },
      { ...validBody, reasoning_effort: 3 },
      { ...validBody, response_format: null },
      null,
      "just a string",
    ]) {
      expect((await worker.fetch(chatRequest(body), env)).status).toBe(400);
    }
    expect(ai.calls).toHaveLength(0);
  });
});

describe("chat route responses", () => {
  test("passes the request through without the model and normalizes chat completions", async () => {
    const ai = fakeAi({
      choices: [{ message: { content: "<p>Hallo</p>" }, finish_reason: "stop" }],
      usage: { prompt_tokens: 12, completion_tokens: 5 },
    });

    const response = await worker.fetch(chatRequest({ ...validBody, reasoning_effort: "low" }), {
      AI: ai,
      EMBEDDINGS_TOKEN: TOKEN,
    });

    expect(response.status).toBe(200);
    expect(await response.json()).toEqual({
      model: MODEL,
      text: "<p>Hallo</p>",
      finish_reason: "stop",
      usage: { input_tokens: 12, output_tokens: 5 },
    });
    expect(ai.calls).toEqual([
      {
        model: MODEL,
        input: {
          messages: validBody.messages,
          max_tokens: 1024,
          reasoning_effort: "low",
        },
      },
    ]);
  });

  // Generated by /ship coverage audit
  // Value: protects=/chat hands Workers AI a valid response_format (JSON mode) and reasoning_effort as sent, and nothing outside its allow-list;
  //   fails_when=response_format is dropped, rewritten or merged, or a field the route does not list (stream, temperature) reaches env.AI.run;
  //   why_new=the pass-through test sends reasoning_effort only, so response_format forwarding and the field allow-list were never asserted;
  //   seam=none;
  //   no_claim=green does not prove Workers AI accepts this response_format shape or that the eval judge builds a valid one.
  test("forwards response_format and reasoning_effort unchanged and drops unlisted body fields", async () => {
    const ai = fakeAi({
      choices: [{ message: { content: '{"score":90}' }, finish_reason: "stop" }],
    });
    const responseFormat = {
      type: "json_schema",
      json_schema: {
        name: "verdict",
        schema: { type: "object", properties: { score: { type: "integer" } }, required: ["score"] },
      },
    };

    const response = await worker.fetch(
      chatRequest({
        ...validBody,
        reasoning_effort: "high",
        response_format: responseFormat,
        stream: true,
        temperature: 2,
      }),
      { AI: ai, EMBEDDINGS_TOKEN: TOKEN },
    );

    expect(response.status).toBe(200);
    expect(ai.calls).toEqual([
      {
        model: MODEL,
        input: {
          messages: validBody.messages,
          max_tokens: 1024,
          reasoning_effort: "high",
          response_format: responseFormat,
        },
      },
    ]);
  });

  // Generated by /ship coverage audit
  // Value: protects=/chat accepts a request sitting exactly on the 400000-char input and 32768 output-token caps and refuses one token more;
  //   fails_when=the char cap or token cap tightens, becomes exclusive, or the token cap loosens by one;
  //   why_new=the validation table only sends clearly oversized bodies (400001 chars, 1000000 tokens), so the accept side of the caps was untested;
  //   seam=none;
  //   no_claim=green does not prove Workers AI itself accepts a 400000-char prompt or a 32768-token completion.
  test("accepts input and output exactly at the caps and rejects one token over", async () => {
    const ai = fakeAi({
      choices: [{ message: { content: "<p>Hallo</p>" }, finish_reason: "stop" }],
    });
    const env = { AI: ai, EMBEDDINGS_TOKEN: TOKEN };
    const messages = [
      { role: "system", content: "x".repeat(200_000) },
      { role: "user", content: "y".repeat(200_000) },
    ];

    const atCaps = await worker.fetch(
      chatRequest({ ...validBody, messages, max_tokens: 32_768 }),
      env,
    );
    expect(atCaps.status).toBe(200);
    expect(ai.calls).toHaveLength(1);
    expect(ai.calls[0]?.input.max_tokens).toBe(32_768);
    expect(ai.calls[0]?.input.messages).toEqual(messages);

    const overTokens = await worker.fetch(chatRequest({ ...validBody, max_tokens: 32_769 }), env);
    expect(overTokens.status).toBe(400);
    expect(ai.calls).toHaveLength(1);
  });

  test("reads Responses API output items and legacy response strings", async () => {
    const env = (result: unknown) => ({ AI: fakeAi(result), EMBEDDINGS_TOKEN: TOKEN });

    const responses = await worker.fetch(
      chatRequest(validBody),
      env({
        output: [
          { type: "reasoning", content: [{ type: "reasoning_text", text: "thinking" }] },
          { type: "message", content: [{ type: "output_text", text: "<p>Hallo</p>" }] },
        ],
        usage: { input_tokens: 3, output_tokens: 4 },
        status: "completed",
      }),
    );
    expect(await responses.json()).toMatchObject({
      text: "<p>Hallo</p>",
      finish_reason: "completed",
      usage: { input_tokens: 3, output_tokens: 4 },
    });

    const legacy = await worker.fetch(chatRequest(validBody), env({ response: { score: 90 } }));
    expect(await legacy.json()).toMatchObject({ text: '{"score":90}' });
  });

  test("returns 502 when Workers AI fails or returns no text", async () => {
    const failing = await worker.fetch(chatRequest(validBody), {
      AI: fakeAi(() => {
        throw new Error("5016: model requires a paid plan");
      }),
      EMBEDDINGS_TOKEN: TOKEN,
    });
    expect(failing.status).toBe(502);
    expect(await failing.json()).toEqual({
      error: "Chat provider failed",
      detail: "5016: model requires a paid plan",
    });

    const empty = await worker.fetch(chatRequest(validBody), {
      AI: fakeAi({ usage: {} }),
      EMBEDDINGS_TOKEN: TOKEN,
    });
    expect(empty.status).toBe(502);
  });

  // Generated by /ship coverage audit
  // Value: protects=/chat reports a usage count as null when the provider sent none, and keeps a reported zero as 0;
  //   fails_when=a missing prompt or completion count becomes 0 or throws instead of null, or a reported 0 turns into null;
  //   why_new=only results with usage counts were tested, so a result without usage was never checked;
  //   seam=none;
  //   no_claim=green does not prove the Workers AI usage fields match what the real models send.
  test("reports absent usage as null and keeps a reported zero", async () => {
    const answer = { message: { content: "<p>Hallo</p>" }, finish_reason: "stop" };
    const env = (result: unknown) => ({ AI: fakeAi(result), EMBEDDINGS_TOKEN: TOKEN });

    const withoutUsage = await worker.fetch(chatRequest(validBody), env({ choices: [answer] }));
    expect(withoutUsage.status).toBe(200);
    expect(await withoutUsage.json()).toEqual({
      model: MODEL,
      text: "<p>Hallo</p>",
      finish_reason: "stop",
      usage: { input_tokens: null, output_tokens: null },
    });

    const emptyUsage = await worker.fetch(
      chatRequest(validBody),
      env({ choices: [answer], usage: {} }),
    );
    expect((await emptyUsage.json()) as { usage: unknown }).toMatchObject({
      usage: { input_tokens: null, output_tokens: null },
    });

    const zeroUsage = await worker.fetch(
      chatRequest(validBody),
      env({ choices: [answer], usage: { prompt_tokens: 0, completion_tokens: 0 } }),
    );
    expect((await zeroUsage.json()) as { usage: unknown }).toMatchObject({
      usage: { input_tokens: 0, output_tokens: 0 },
    });
  });

  // Generated by /ship coverage audit
  // Value: protects=an eval run never mistakes a model that produced no answer for an empty successful translation, as /chat answers 502;
  //   fails_when=a reasoning-only Responses result (status incomplete) or an empty chat completion returns 200 with text "" instead of 502;
  //   why_new=the 502 test only covers a result with no recognised text field, so empty-text results were never exercised;
  //   seam=none;
  //   no_claim=green does not prove real gpt-oss output shapes or that callers retry on a 502.
  test("returns 502 when a Responses result holds only a reasoning item", async () => {
    const response = await worker.fetch(chatRequest(validBody), {
      AI: fakeAi({
        output: [
          {
            type: "reasoning",
            content: [{ type: "reasoning_text", text: "thinking, then ran out" }],
          },
        ],
        status: "incomplete",
        usage: { input_tokens: 40, output_tokens: 1024 },
      }),
      EMBEDDINGS_TOKEN: TOKEN,
    });

    expect(response.status).toBe(502);
    expect(await response.json()).toMatchObject({ error: "Chat provider returned no text" });
  });

  // Generated by /ship coverage audit
  // Value: protects=/chat answers 502 rather than 200 with empty text when a chat completion carries empty message content;
  //   fails_when=choices[0].message.content is "" and the route returns 200 instead of 502;
  //   why_new=empty-string content was never exercised, and the 502 test only covers results with no text field;
  //   seam=none;
  //   no_claim=green does not prove how real models signal a length-truncated completion.
  test("returns 502 when a chat completion carries empty message content", async () => {
    const response = await worker.fetch(chatRequest(validBody), {
      AI: fakeAi({
        choices: [{ message: { content: "" }, finish_reason: "length" }],
        usage: { prompt_tokens: 40, completion_tokens: 1024 },
      }),
      EMBEDDINGS_TOKEN: TOKEN,
    });

    expect(response.status).toBe(502);
    expect(await response.json()).toMatchObject({ error: "Chat provider returned no text" });
  });
});
