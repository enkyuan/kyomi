import { Effect, Layer } from "effect";
import { ARTICLE_HTML_SANITIZER_VERSION } from "@kyomi/reader/sanitization";
import { getClipDetailForUser } from "@modules/articles/write/clips/detail";
import {
  createArticleClip,
  updateArticleClipForUser,
} from "@modules/articles/write/clips/operations";
import { fakeDb, fakeQueue, recordingLogger, silentLogger } from "@api-tests/support/layers";

function pendingClipRow(overrides: Record<string, unknown> = {}) {
  return {
    id: "clip_1",
    userId: "user_1",
    url: "https://example.com/article",
    title: "example.com",
    content: null,
    contentHtml: null,
    contentText: null,
    contentMarkdown: null,
    contentStatus: "pending",
    contentSource: "link_only",
    extractionErrorCode: null,
    extractionErrorMessage: null,
    extractedContentHtml: null,
    extractedContentText: null,
    extractedContentStatus: "pending",
    extractedContentError: null,
    extractedContentUpdatedAt: null,
    note: null,
    isRead: false,
    isSaved: true,
    createdAt: new Date("2026-04-08T10:00:00.000Z"),
    updatedAt: new Date("2026-04-08T10:00:00.000Z"),
    ...overrides,
  };
}

type InsertFake = {
  values?: (row: Record<string, unknown>) => void;
  returning?: (fields: Record<string, unknown>) => void;
  update?: ReturnType<typeof mock>;
};

/** A Drizzle fake whose insert returns `row`; `update` stands in for marking extraction failed. */
function insertingDb(row: Record<string, unknown>, hooks: InsertFake = {}) {
  const returning = mock((fields: Record<string, unknown>) => {
    hooks.returning?.(fields);
    return Promise.resolve([row]);
  });
  const values = mock((inserted: Record<string, unknown>) => {
    hooks.values?.(inserted);
    return { returning };
  });
  const insert = mock(() => ({ values }));
  return { insert, values, returning, layer: fakeDb({ insert, update: hooks.update }) };
}

/** `xadd(stream, "MAXLEN", "~", max, "*", ...fields)` calls, decoded to `{ type, payload }`. */
function publishedJobs(xadd: ReturnType<typeof mock>) {
  return xadd.mock.calls.map((call) => {
    const fields = (call as unknown[]).slice(5) as string[];
    const at = (name: string) => fields[fields.indexOf(name) + 1]!;
    return { type: at("type"), payload: JSON.parse(at("payload")) as Record<string, any> };
  });
}

function runCreate(
  layer: Layer.Layer<any, any>,
  body: Parameters<typeof createArticleClip>[1],
  logs = recordingLogger(),
) {
  return Effect.runPromise(
    createArticleClip("user_1", body).pipe(Effect.provide(Layer.mergeAll(layer, logs.layer))),
  );
}

describe("createArticleClip", () => {
  test("persists a pending link-only clip and queues extraction without fetching", async () => {
    const xadd = mock(async () => "stream-id-1");
    const db = insertingDb(pendingClipRow());
    const logs = recordingLogger();

    const result = await runCreate(
      Layer.mergeAll(db.layer, fakeQueue({ xadd })),
      { url: "https://example.com/article" },
      logs,
    );

    expect(result.contentStatus).toBe("pending");
    expect(result.contentHtml).toBeNull();
    const jobs = publishedJobs(xadd);
    expect(jobs).toHaveLength(1);
    expect(jobs[0]).toMatchObject({
      type: "article.extract",
      payload: {
        articleId: "clip_1",
        userId: "user_1",
        reason: "clip_created",
        replaceClipTitle: true,
        autogeneratedTitleAtQueue: "example.com",
      },
    });
    expect(logs.entries).toEqual([
      expect.objectContaining({
        level: "info",
        event: "articles.clip.created",
        context: { userId: "user_1", clipId: "clip_1" },
      }),
    ]);
  });

  test("does not enqueue extraction when explicit content is provided", async () => {
    const xadd = mock(async () => "stream-id-1");
    const db = insertingDb(
      pendingClipRow({
        title: "My title",
        content: "Explicit content",
        contentText: "Explicit content",
        contentStatus: "partial",
        contentSource: "text_fallback",
      }),
    );

    const result = await runCreate(Layer.mergeAll(db.layer, fakeQueue({ xadd })), {
      url: "https://example.com/article",
      title: "My title",
      content: "Explicit content",
    });

    expect(result.contentText).toBe("Explicit content");
    expect(xadd).not.toHaveBeenCalled();
  });

  test("marks replaceClipTitle false when the user supplied an explicit title", async () => {
    const xadd = mock(async () => "stream-id-1");
    const db = insertingDb(pendingClipRow({ title: "User title" }));

    await runCreate(Layer.mergeAll(db.layer, fakeQueue({ xadd })), {
      url: "https://example.com/article",
      title: "User title",
    });

    const [job] = publishedJobs(xadd);
    expect(job!.payload.replaceClipTitle).toBe(false);
    expect(job!.payload.autogeneratedTitleAtQueue).toBeUndefined();
  });

  test("queue publication failure leaves the clip committed with a failed extracted state, logs it, and still returns the detail", async () => {
    const xadd = mock(() => Promise.reject(new Error("redis unavailable")));
    const updateWhere = mock(() => Promise.resolve());
    const updateSet = mock(() => ({ where: updateWhere }));
    const update = mock(() => ({ set: updateSet }));
    const db = insertingDb(pendingClipRow(), { update });
    const logs = recordingLogger();

    const result = await runCreate(
      Layer.mergeAll(db.layer, fakeQueue({ xadd })),
      { url: "https://example.com/article" },
      logs,
    );

    expect(result.id).toBe("clip_1");
    expect(update).toHaveBeenCalledTimes(1);
    expect(updateSet).toHaveBeenCalledWith(
      expect.objectContaining({ extractedContentStatus: "failed" }),
    );
    expect(logs.entries.map((entry) => `${entry.level} ${entry.event}`)).toEqual([
      "warn articles.clip.extraction_enqueue_failed",
      "info articles.clip.created",
    ]);
  });

  test("a failure to record the failed extraction state fails the request instead of being swallowed", async () => {
    const xadd = mock(() => Promise.reject(new Error("redis unavailable")));
    const update = mock(() => ({
      set: () => ({ where: () => Promise.reject(new Error("db down")) }),
    }));
    const db = insertingDb(pendingClipRow(), { update });

    const error = await Effect.runPromise(
      createArticleClip("user_1", { url: "https://example.com/article" }).pipe(
        Effect.provide(Layer.mergeAll(db.layer, fakeQueue({ xadd }), recordingLogger().layer)),
        Effect.flip,
      ),
    );

    expect(error._tag).toBe("DatabaseError");
  });

  test("rejects explicit content over the 1 MiB field budget without touching the database", async () => {
    const db = insertingDb(pendingClipRow());

    const error = await Effect.runPromise(
      createArticleClip("user_1", {
        url: "https://example.com/article",
        content: "a".repeat(1024 * 1024 + 1),
      }).pipe(
        Effect.provide(Layer.mergeAll(db.layer, fakeQueue(), recordingLogger().layer)),
        Effect.flip,
      ),
    );

    expect(error).toMatchObject({ _tag: "PayloadTooLarge", code: "ARTICLE_CONTENT_TOO_LARGE" });
    expect(db.insert).not.toHaveBeenCalled();
  });

  test("accepts explicit content at exactly the 1 MiB field budget", async () => {
    const db = insertingDb(
      pendingClipRow({
        title: "My title",
        content: "a".repeat(1024 * 1024),
        contentText: "a".repeat(1024 * 1024),
        contentStatus: "partial",
        contentSource: "text_fallback",
      }),
    );

    await expect(
      runCreate(Layer.mergeAll(db.layer, fakeQueue()), {
        url: "https://example.com/article",
        title: "My title",
        content: "a".repeat(1024 * 1024),
      }),
    ).resolves.toMatchObject({ title: "My title" });
  });

  test("rejects a blank or non-http url with its public code", async () => {
    const db = insertingDb(pendingClipRow());
    const fail = (url: string) =>
      Effect.runPromise(
        createArticleClip("user_1", { url }).pipe(
          Effect.provide(Layer.mergeAll(db.layer, fakeQueue(), recordingLogger().layer)),
          Effect.flip,
        ),
      );

    expect(await fail("   ")).toMatchObject({ _tag: "BadRequest", code: "CLIP_URL_REQUIRED" });
    expect(await fail("ftp://example.com/a")).toMatchObject({
      _tag: "BadRequest",
      code: "INVALID_CLIP_URL",
    });
    expect(await fail("not a url")).toMatchObject({ code: "INVALID_CLIP_URL" });
    expect(db.insert).not.toHaveBeenCalled();
  });

  test("an insert that returns no row is a CLIP_CREATE_FAILED internal error", async () => {
    const insert = () => ({ values: () => ({ returning: () => Promise.resolve([]) }) });

    const error = await Effect.runPromise(
      createArticleClip("user_1", { url: "https://example.com/article" }).pipe(
        Effect.provide(Layer.mergeAll(fakeDb({ insert }), fakeQueue(), recordingLogger().layer)),
        Effect.flip,
      ),
    );

    expect(error).toMatchObject({ _tag: "InternalError", code: "CLIP_CREATE_FAILED" });
  });
});

const RAW_COLUMNS = ["contentRaw", "extractedContentRaw"];

/** Everything a clip update can touch: the database, the job queue and the logger. */
const clipServices = (db: object) => Layer.mergeAll(fakeDb(db as never), fakeQueue(), silentLogger);

function selectingDb(row: Record<string, unknown>) {
  const selected: Record<string, unknown>[] = [];
  const updates: Record<string, unknown>[] = [];
  const db = {
    selected,
    updates,
    select: (fields: Record<string, unknown>) => {
      selected.push(fields);
      const filtered = { where: () => ({ limit: () => Promise.resolve([row]) }) };
      // Clip detail left joins the reading state before filtering.
      return { from: () => ({ ...filtered, leftJoin: () => filtered }) };
    },
    update: () => ({
      set: (patch: Record<string, unknown>) => {
        updates.push(patch);
        return { where: () => Promise.resolve() };
      },
    }),
  };
  return db;
}

describe("clip raw source", () => {
  test("create compiles HTML content, keeps the raw body, and never returns raw columns", async () => {
    const content = `<p>Read <a href="/docs">the docs</a>.</p><iframe src="https://www.youtube.com/embed/dQw4w9WgXcQ" title="Talk"></iframe>`;
    const db = insertingDb(pendingClipRow({ content, contentStatus: "ready" }), {
      values: (row) => {
        expect(row.contentRaw).toBe(content);
        expect(row.contentSanitizerVersion).toBe(ARTICLE_HTML_SANITIZER_VERSION);
        expect(String(row.contentHtml)).toContain('href="https://example.com/docs"');
        expect(String(row.contentHtml)).toContain('data-kyomi-embed="youtube"');
        expect(String(row.contentHtml)).not.toContain("<iframe");
      },
      returning: (fields) => {
        expect(Object.keys(fields)).not.toContain("contentRaw");
        expect(Object.keys(fields)).not.toContain("extractedContentRaw");
      },
    });

    await runCreate(Layer.mergeAll(db.layer, fakeQueue()), {
      url: "https://example.com/article",
      title: "Docs",
      content,
    });

    expect(db.values).toHaveBeenCalledTimes(1);
    expect(db.returning).toHaveBeenCalledTimes(1);
  });

  test("update compiles client HTML and stores it as raw source", async () => {
    const db = selectingDb(pendingClipRow());
    const contentHtml = `<p data-kyomi-url="javascript:alert(1)">Clipped <img src="data:image/gif;base64,R0" data-src="hero.png" alt="Hero"></p>`;

    await Effect.runPromise(
      updateArticleClipForUser("user_1", "clip_1", { contentHtml }).pipe(
        Effect.provide(clipServices(db)),
      ),
    );

    for (const fields of db.selected) {
      expect(Object.keys(fields)).not.toEqual(expect.arrayContaining(RAW_COLUMNS));
    }
    const patch = db.updates[0]!;
    expect(patch.contentRaw).toBe(contentHtml);
    expect(patch.contentSanitizerVersion).toBe(ARTICLE_HTML_SANITIZER_VERSION);
    expect(String(patch.contentHtml)).toContain('src="https://example.com/hero.png"');
    expect(String(patch.contentHtml)).not.toContain("data-kyomi-url");
  });

  test("update that leaves contentHtml alone does not touch the raw columns", async () => {
    const db = selectingDb(pendingClipRow());

    await Effect.runPromise(
      updateArticleClipForUser("user_1", "clip_1", { note: "Later" }).pipe(
        Effect.provide(clipServices(db)),
      ),
    );

    expect(db.updates[0]).not.toHaveProperty("contentRaw");
    expect(db.updates[0]).not.toHaveProperty("contentSanitizerVersion");
  });

  test("update of a clip the user does not own is not found", async () => {
    const db = {
      select: () => ({ from: () => ({ where: () => ({ limit: () => Promise.resolve([]) }) }) }),
    };

    const error = await Effect.runPromise(
      updateArticleClipForUser("user_1", "clip_9", { note: "x" }).pipe(
        Effect.provide(clipServices(db)),
        Effect.flip,
      ),
    );

    expect(error).toMatchObject({ _tag: "NotFound", code: "ARTICLE_NOT_FOUND" });
  });

  test("an update with no fields is rejected before any query", async () => {
    const error = await Effect.runPromise(
      updateArticleClipForUser("user_1", "clip_1", {}).pipe(
        Effect.provide(clipServices({})),
        Effect.flip,
      ),
    );

    expect(error).toMatchObject({ _tag: "BadRequest", code: "EMPTY_UPDATE" });
  });

  test("clip detail selects explicit columns and serializes no raw source", async () => {
    const db = selectingDb(
      pendingClipRow({ contentRaw: "<p>RAW-MARKER</p>", extractedContentRaw: "<p>RAW-MARKER</p>" }),
    );

    const detail = await getClipDetailForUser(db as never, "user_1", "clip_1");

    expect(Object.keys(db.selected[0]!)).not.toEqual(expect.arrayContaining(["contentRaw"]));
    expect(Object.keys(db.selected[0]!)).not.toEqual(
      expect.arrayContaining(["extractedContentRaw"]),
    );
    expect(JSON.stringify(detail)).not.toContain("RAW-MARKER");
  });
});
