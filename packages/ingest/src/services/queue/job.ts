export const FEED_REFRESH_JOBS_STREAM_KEY = "jobs:feed-refresh";
export const OPML_JOBS_STREAM_KEY = "jobs:opml";
export const ARTICLE_EXTRACTION_JOBS_STREAM_KEY = "jobs:article-extraction";
export const DOCUMENT_ENRICHMENT_JOBS_STREAM_KEY = "jobs:document-enrichment";
export const JOBS_STREAM_KEY = FEED_REFRESH_JOBS_STREAM_KEY;
export const JOBS_CONSUMER_GROUP = "kyomi-workers";
export const JOBS_DEAD_LETTER_STREAM_KEY = "jobs:dead-letter";

export type FeedRefreshJob = {
  type: "feed.refresh";
  payload: {
    feedId: string;
    userId: string;
    reason?: string;
    generation?: number;
  };
};

export type OpmlImportJob = {
  type: "opml.import";
  payload: {
    taskId: string;
    userId: string;
    xml: string;
    filename: string;
  };
};

export type OpmlImportFeedJob = {
  type: "opml.import.feed";
  payload: {
    taskId: string;
    userId: string;
    url: string;
    title?: string;
    folderId?: string | null;
  };
};

/** Wakeup carrying only an import id; the worker loads durable state from Postgres. */
export type OpmlImportPrepareJob = {
  type: "opml.import.prepare";
  payload: {
    importId: string;
  };
};

/** Leased-item wakeup; the worker loads the item's URL/title/folder from Postgres by id. */
export type OpmlImportItemJob = {
  type: "opml.import.item";
  payload: {
    importId: string;
    itemId: string;
    leaseToken: string;
  };
};

export type ArticleExtractionJob = {
  type: "article.extract";
  payload: {
    articleId: string;
    userId: string;
    requestedAt: string;
    reason?:
      | "manual"
      | "prefetch"
      | "scheduled"
      | "global_scheduled"
      | "subscription_created"
      | "clip_created";
    /** True only when the clip's current title was autogenerated, not user-supplied. */
    replaceClipTitle?: boolean;
    /** The autogenerated title present when this job was queued; used to detect user edits. */
    autogeneratedTitleAtQueue?: string;
  };
};

/** Content row that owns a stored KDM document. Feed items are shared across users. */
export type DocumentTarget = {
  table: "feed_items" | "article_clips";
  id: string;
  body: "original" | "extracted";
};

/** Probes missing image dimensions and placeholders in a stored KDM document. */
export type DocumentImageMeasureJob = {
  type: "document.image-measure";
  payload: { target: DocumentTarget };
};

/** Fetches `embed.snapshot` for X, Bluesky, Mastodon, Threads, and Instagram embeds. */
export type DocumentEmbedSnapshotJob = {
  type: "document.embed-snapshot";
  payload: { target: DocumentTarget };
};

export type Job =
  | FeedRefreshJob
  | OpmlImportJob
  | OpmlImportFeedJob
  | OpmlImportPrepareJob
  | OpmlImportItemJob
  | ArticleExtractionJob
  | DocumentImageMeasureJob
  | DocumentEmbedSnapshotJob;
export type JobType = Job["type"];

export type JobMessage = {
  id: string;
  job: Job;
  attempts: number;
  rawFields: Record<string, string>;
};

export type QueueOptions = {
  streamKey?: string;
  streamMaxLength?: number;
  processConcurrency?: number;
};

export function getStreamKeyForJobType(jobType: JobType): string {
  switch (jobType) {
    case "feed.refresh":
      return FEED_REFRESH_JOBS_STREAM_KEY;
    case "opml.import":
    case "opml.import.feed":
    case "opml.import.prepare":
    case "opml.import.item":
      return OPML_JOBS_STREAM_KEY;
    case "article.extract":
      return ARTICLE_EXTRACTION_JOBS_STREAM_KEY;
    case "document.image-measure":
    case "document.embed-snapshot":
      return DOCUMENT_ENRICHMENT_JOBS_STREAM_KEY;
  }
}

export function normalizeQueueOptions(options: QueueOptions = {}) {
  return {
    streamKey: options.streamKey,
    streamMaxLength: Math.min(Math.max(options.streamMaxLength ?? 100_000, 1_000), 5_000_000),
    processConcurrency: Math.min(Math.max(options.processConcurrency ?? 1, 1), 64),
  };
}

export function fieldsForJob(
  job: Job,
  metadata?: { attempts?: number; lastError?: string | null },
): Record<string, string> {
  const fields: Record<string, string> = {
    type: job.type,
    payload: JSON.stringify(job.payload),
  };
  if (metadata?.attempts !== undefined) {
    fields.attempts = String(metadata.attempts);
  }
  if (metadata?.lastError) {
    fields.last_error = metadata.lastError;
  }
  return fields;
}

export function toRedisStreamFieldList(
  fields: Record<string, string>,
): [string, string, ...string[]] {
  const entries = Object.entries(fields).flatMap(([key, value]) => [key, value]);

  if (entries.length < 2) {
    throw new Error("Redis stream field list requires at least one field");
  }

  return entries as [string, string, ...string[]];
}

function parseFeedRefreshJob(parsedPayload: Record<string, unknown>): FeedRefreshJob {
  if (typeof parsedPayload.feedId !== "string" || typeof parsedPayload.userId !== "string") {
    throw new Error("Invalid feed.refresh payload");
  }

  const generation = parsedPayload.generation as number | undefined;
  if (generation !== undefined && (!Number.isInteger(generation) || generation < 0)) {
    throw new Error("Invalid feed.refresh payload");
  }

  return {
    type: "feed.refresh",
    payload: {
      feedId: parsedPayload.feedId,
      userId: parsedPayload.userId,
      reason: typeof parsedPayload.reason === "string" ? parsedPayload.reason : undefined,
      generation,
    },
  };
}

function parseOpmlImportJob(parsedPayload: Record<string, unknown>): OpmlImportJob {
  if (
    typeof parsedPayload.taskId !== "string" ||
    typeof parsedPayload.userId !== "string" ||
    typeof parsedPayload.xml !== "string" ||
    typeof parsedPayload.filename !== "string"
  ) {
    throw new Error("Invalid opml.import payload");
  }

  return {
    type: "opml.import",
    payload: {
      taskId: parsedPayload.taskId,
      userId: parsedPayload.userId,
      xml: parsedPayload.xml,
      filename: parsedPayload.filename,
    },
  };
}

function parseOpmlImportFeedJob(parsedPayload: Record<string, unknown>): OpmlImportFeedJob {
  if (
    typeof parsedPayload.taskId !== "string" ||
    typeof parsedPayload.userId !== "string" ||
    typeof parsedPayload.url !== "string"
  ) {
    throw new Error("Invalid opml.import.feed payload");
  }

  return {
    type: "opml.import.feed",
    payload: {
      taskId: parsedPayload.taskId,
      userId: parsedPayload.userId,
      url: parsedPayload.url,
      title: typeof parsedPayload.title === "string" ? parsedPayload.title : undefined,
      folderId:
        typeof parsedPayload.folderId === "string"
          ? parsedPayload.folderId
          : parsedPayload.folderId === null
            ? null
            : undefined,
    },
  };
}

function parseOpmlImportPrepareJob(parsedPayload: Record<string, unknown>): OpmlImportPrepareJob {
  if (typeof parsedPayload.importId !== "string" || parsedPayload.importId.length === 0) {
    throw new Error("Invalid opml.import.prepare payload");
  }
  return {
    type: "opml.import.prepare",
    payload: { importId: parsedPayload.importId },
  };
}

function parseOpmlImportItemJob(parsedPayload: Record<string, unknown>): OpmlImportItemJob {
  if (
    typeof parsedPayload.importId !== "string" ||
    typeof parsedPayload.itemId !== "string" ||
    typeof parsedPayload.leaseToken !== "string" ||
    parsedPayload.importId.length === 0 ||
    parsedPayload.itemId.length === 0 ||
    parsedPayload.leaseToken.length === 0
  ) {
    throw new Error("Invalid opml.import.item payload");
  }
  return {
    type: "opml.import.item",
    payload: {
      importId: parsedPayload.importId,
      itemId: parsedPayload.itemId,
      leaseToken: parsedPayload.leaseToken,
    },
  };
}

function parseArticleExtractionReason(value: unknown): ArticleExtractionJob["payload"]["reason"] {
  switch (value) {
    case "manual":
    case "prefetch":
    case "scheduled":
    case "global_scheduled":
    case "subscription_created":
    case "clip_created":
      return value;
    default:
      return undefined;
  }
}

function parseArticleExtractionJob(parsedPayload: Record<string, unknown>): ArticleExtractionJob {
  if (
    typeof parsedPayload.articleId !== "string" ||
    typeof parsedPayload.userId !== "string" ||
    typeof parsedPayload.requestedAt !== "string"
  ) {
    throw new Error("Invalid article.extract payload");
  }
  if (
    parsedPayload.replaceClipTitle !== undefined &&
    typeof parsedPayload.replaceClipTitle !== "boolean"
  ) {
    throw new Error("Invalid article.extract payload: replaceClipTitle must be a boolean");
  }
  if (
    parsedPayload.autogeneratedTitleAtQueue !== undefined &&
    parsedPayload.replaceClipTitle !== true
  ) {
    throw new Error(
      "Invalid article.extract payload: autogeneratedTitleAtQueue requires replaceClipTitle true",
    );
  }
  if (
    parsedPayload.autogeneratedTitleAtQueue !== undefined &&
    typeof parsedPayload.autogeneratedTitleAtQueue !== "string"
  ) {
    throw new Error("Invalid article.extract payload: autogeneratedTitleAtQueue must be a string");
  }

  return {
    type: "article.extract",
    payload: {
      articleId: parsedPayload.articleId,
      userId: parsedPayload.userId,
      requestedAt: parsedPayload.requestedAt,
      reason: parseArticleExtractionReason(parsedPayload.reason),
      replaceClipTitle: parsedPayload.replaceClipTitle as boolean | undefined,
      autogeneratedTitleAtQueue: parsedPayload.autogeneratedTitleAtQueue as string | undefined,
    },
  };
}

function parseDocumentTarget(value: unknown): DocumentTarget | null {
  if (typeof value !== "object" || value === null) return null;
  const { table, id, body } = value as Record<string, unknown>;
  if ((table !== "feed_items" && table !== "article_clips") || typeof id !== "string" || !id) {
    return null;
  }
  if (body !== "original" && body !== "extracted") return null;
  return { table, id, body };
}

function parseDocumentEnrichmentJob(
  type: "document.image-measure" | "document.embed-snapshot",
  parsedPayload: Record<string, unknown>,
): DocumentImageMeasureJob | DocumentEmbedSnapshotJob {
  const target = parseDocumentTarget(parsedPayload.target);
  if (!target) {
    throw new Error(`Invalid ${type} payload`);
  }
  return { type, payload: { target } };
}

export function parseJob(fields: Record<string, string>): Job {
  const parsedPayload = JSON.parse(fields.payload ?? "null") as Record<string, unknown> | null;
  if (!parsedPayload) {
    throw new Error(`Invalid ${fields.type ?? "unknown"} payload`);
  }

  switch (fields.type) {
    case "feed.refresh":
      return parseFeedRefreshJob(parsedPayload);
    case "opml.import":
      return parseOpmlImportJob(parsedPayload);
    case "opml.import.feed":
      return parseOpmlImportFeedJob(parsedPayload);
    case "opml.import.prepare":
      return parseOpmlImportPrepareJob(parsedPayload);
    case "opml.import.item":
      return parseOpmlImportItemJob(parsedPayload);
    case "article.extract":
      return parseArticleExtractionJob(parsedPayload);
    case "document.image-measure":
    case "document.embed-snapshot":
      return parseDocumentEnrichmentJob(fields.type, parsedPayload);
    default:
      throw new Error(`Unsupported job type: ${fields.type ?? "unknown"}`);
  }
}

export function parseJobMessageFields(id: string, fields: Record<string, string>): JobMessage {
  const attemptsRaw = Number(fields.attempts ?? "0");
  const attempts = Number.isFinite(attemptsRaw) && attemptsRaw >= 0 ? attemptsRaw : 0;
  return {
    id,
    job: parseJob(fields),
    attempts,
    rawFields: fields,
  };
}
