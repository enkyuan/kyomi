import { DateTime, Effect } from "effect";
import { Db } from "@adapters/db/service";
import { articleClips, feedItems } from "@kyomi/db";
import { enqueueEnrichmentForStoredDocument } from "@modules/articles/document/enrich";
import type { ArticleDetailDto } from "@modules/articles/types";
import { toStoredDocumentColumns, type StoredDocument } from "@kyomi/ingest/lib/stored-document";
import { and, eq, isNull, ne, or } from "drizzle-orm";

export type ExtractedPersistencePayload =
  | {
      kind: "ready";
      html: string;
      text: string;
      sanitizerVersion: string;
      /** Readability output before compiling, when known. */
      raw: string | null;
      /** KDM document compiled from `raw`; null leaves the HTML body to serve alone. */
      document?: StoredDocument | null;
      title?: string | null;
    }
  | { kind: "failed"; message: string };
export type TitleReplacement = { replaceClipTitle: boolean; autogeneratedTitleAtQueue?: string };

/** The `extracted*` columns feed items and clips share, so one patch updates either table. */
function extractedPatch(payload: ExtractedPersistencePayload, now: Date) {
  if (payload.kind === "ready") {
    const document = toStoredDocumentColumns(payload.document ?? null);
    return {
      extractedContentHtml: payload.html,
      extractedContentText: payload.text,
      extractedContentSanitizerVersion: payload.sanitizerVersion,
      extractedContentRaw: payload.raw,
      extractedContentDocument: document.document,
      extractedContentDocumentVersion: document.documentVersion,
      extractedContentCompilerVersion: document.compilerVersion,
      extractedContentStatus: "ready",
      extractedContentError: null,
      extractedContentUpdatedAt: now,
      updatedAt: now,
    } as const;
  }
  return {
    extractedContentHtml: null,
    extractedContentText: null,
    extractedContentSanitizerVersion: null,
    extractedContentRaw: null,
    extractedContentDocument: null,
    extractedContentDocumentVersion: null,
    extractedContentCompilerVersion: null,
    extractedContentStatus: "failed",
    extractedContentError: payload.message,
    extractedContentUpdatedAt: now,
    updatedAt: now,
  } as const;
}

/**
 * Claim an article for a queued extraction: mark it pending and report whether this call won.
 * The claim is one conditional UPDATE, so two concurrent requests cannot both enqueue a job. An
 * article that is already pending with a request timestamp is left alone and reports `false`.
 */
export const claimPendingExtraction = Effect.fn("extraction.persist.claimPending")(function* (
  article: ArticleDetailDto,
) {
  const db = yield* Db;
  const now = yield* DateTime.nowAsDate;
  const pending = {
    extractedContentStatus: "pending",
    extractedContentError: null,
    extractedContentUpdatedAt: now,
    updatedAt: now,
  } as const;
  const claimed = yield* db.use("claim pending extraction", (client) =>
    article.articleType === "feed"
      ? client
          .update(feedItems)
          .set(pending)
          .where(
            and(
              eq(feedItems.id, article.id),
              or(
                ne(feedItems.extractedContentStatus, "pending"),
                isNull(feedItems.extractedContentUpdatedAt),
              ),
            ),
          )
          .returning({ id: feedItems.id })
      : client
          .update(articleClips)
          .set(pending)
          .where(
            and(
              eq(articleClips.id, article.id),
              or(
                ne(articleClips.extractedContentStatus, "pending"),
                isNull(articleClips.extractedContentUpdatedAt),
              ),
            ),
          )
          .returning({ id: articleClips.id }),
  );
  return claimed.length > 0;
});

export const persistExtracted = Effect.fn("extraction.persist.extracted")(function* (
  article: ArticleDetailDto,
  payload: ExtractedPersistencePayload,
  titleReplacement?: TitleReplacement,
) {
  const db = yield* Db;
  const now = yield* DateTime.nowAsDate;
  const patch = extractedPatch(payload, now);

  yield* db.use("update extracted content", (client) =>
    article.articleType === "feed"
      ? client.update(feedItems).set(patch).where(eq(feedItems.id, article.id))
      : client.update(articleClips).set(patch).where(eq(articleClips.id, article.id)),
  );

  const extractedTitle = payload.kind === "ready" ? payload.title?.trim() || null : null;
  const autogeneratedTitle = titleReplacement?.autogeneratedTitleAtQueue;
  if (
    article.articleType === "clip" &&
    titleReplacement?.replaceClipTitle &&
    autogeneratedTitle &&
    extractedTitle
  ) {
    // Only overwrite the title if it still equals the autogenerated title captured when
    // the job was queued: a mismatch means the user edited it since, which must win.
    yield* db.use("replace clip title", (client) =>
      client
        .update(articleClips)
        .set({ title: extractedTitle, updatedAt: now })
        .where(and(eq(articleClips.id, article.id), eq(articleClips.title, autogeneratedTitle))),
    );
  }

  if (payload.kind === "ready" && payload.document) {
    // Best effort by contract: enqueueing enrichment logs its own failures and never fails the write.
    yield* enqueueEnrichmentForStoredDocument(
      {
        table: article.articleType === "feed" ? "feed_items" : "article_clips",
        id: article.id,
        body: "extracted",
      },
      payload.document.document,
    );
  }
});
