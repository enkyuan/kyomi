import { DateTime, Effect } from "effect";
import { AppLogger } from "@adapters/logger/service";
import { JobQueue } from "@adapters/queue/service";
import { AppConfig } from "@config/env/service";
import { embeddingClassifierConfig } from "@config/embeddings";
import { assertHttpOrHttpsUrl } from "@modules/discover/feed/normalize";
import {
  ARTICLE_HTML_SANITIZER_VERSION,
  processArticleHtml,
} from "@modules/articles/reader/content";
import { getArticleDetail } from "@modules/articles/read/detail";
import type { ArticleDetailDto } from "@modules/articles/types";
import type { EmbeddingClassifierConfig, HostRateLimiter } from "@kyomi/ingest";
import {
  compileStoredDocument,
  currentCompilerVersion,
  type StoredDocument,
} from "@kyomi/ingest/lib/stored-document";
import { unexpected } from "@shared/effect/errors";
import { serializeError } from "@shared/errors/serialize";
import {
  normalizeExtractionUrlKey,
  readFreshExtractionCache,
  safeExtractErrorMessage,
  upsertFailedExtractionCache,
  upsertReadyExtractionCache,
  type FreshExtractionCache,
} from "./cache";
import type { ExtractionFailed } from "./errors";
import { claimPendingExtraction, persistExtracted, type TitleReplacement } from "./persistence";
import { compileExtractedHtml, extractArticleContentFromUrl } from "./readability";
import { reclassifyExtractedFeedItem } from "./reclassify";

type ExtractFullTextOptions = {
  /** Defaults to the embeddings Worker in `AppConfig`; absent there too means keyword-only. */
  embeddingClassifier?: EmbeddingClassifierConfig;
  hostRateLimiter?: HostRateLimiter;
  /** Only replace the clip's autogenerated title, and only if the user hasn't since edited it. */
  titleReplacement?: TitleReplacement;
};

/** Bounds each embeddings request so a stalled Worker cannot hold the request or the job. */
const EMBEDDING_TIMEOUT_MS = 8000;

const compileExtractedDocument = (
  raw: string | null,
  baseUrl: string | null,
  title: string | null,
) =>
  raw
    ? Effect.tryPromise({
        try: (): Promise<StoredDocument | null> =>
          compileStoredDocument({ raw, format: "html", origin: "extracted_html", baseUrl, title }),
        catch: unexpected,
      })
    : Effect.succeed(null);

/** Record a failed extraction on the article and answer with it. */
const recordFailure = Effect.fn("extraction.recordFailure")(function* (
  userId: string,
  before: ArticleDetailDto,
  errorCode: string,
  errorMessage: string,
) {
  yield* persistExtracted(before, { kind: "failed", message: errorMessage });
  const article = yield* getArticleDetail(userId, before.id);
  return { ok: false, status: "failed", errorCode, errorMessage, article } as const;
});

const applyFreshExtractionCache = Effect.fn("extraction.applyCache")(function* (
  userId: string,
  article: ArticleDetailDto,
  cached: FreshExtractionCache | null,
  options: ExtractFullTextOptions,
) {
  if (!cached) {
    return null;
  }

  if (cached.kind === "failed") {
    return yield* recordFailure(userId, article, cached.errorCode, cached.message);
  }

  // A stale cache row is recompiled from its raw Readability output when it has one, so it
  // gains the current compiler; older rows without raw source are only re-sanitized.
  const stale = cached.sanitizerVersion !== ARTICLE_HTML_SANITIZER_VERSION;
  const processed =
    stale && cached.rawHtml
      ? compileExtractedHtml(cached.rawHtml, { baseUrl: cached.finalUrl })
      : processArticleHtml(cached.html, { sanitizerVersion: cached.sanitizerVersion });
  const text = stale && cached.rawHtml ? processed.text : cached.text;
  // Reuse the cached document unless the compiler moved on and raw source can rebuild it.
  const document =
    cached.document && cached.document.compilerVersion === currentCompilerVersion()
      ? cached.document
      : yield* compileExtractedDocument(
          cached.rawHtml,
          cached.finalUrl ?? article.link,
          article.title,
        );
  yield* persistExtracted(
    article,
    {
      kind: "ready",
      html: processed.html,
      text,
      sanitizerVersion: processed.sanitizerVersion,
      raw: cached.rawHtml,
      document,
      title: null,
    },
    options.titleReplacement,
  );
  if (article.articleType === "feed") {
    yield* reclassifyExtractedFeedItem(article, text, options.embeddingClassifier);
  }
  const updatedArticle = yield* getArticleDetail(userId, article.id);
  return { ok: true, status: "ready", article: updatedArticle } as const;
});

function parseSourceUrl(link: string): URL | null {
  try {
    return assertHttpOrHttpsUrl(link);
  } catch {
    return null;
  }
}

/** Validate the article's link and short-circuit what needs no extraction. */
const prepareExtraction = Effect.fn("extraction.prepare")(function* (
  userId: string,
  articleId: string,
) {
  const before = yield* getArticleDetail(userId, articleId);

  const sourceUrl = parseSourceUrl(before.link);
  if (!sourceUrl) {
    const result = yield* recordFailure(
      userId,
      before,
      "INVALID_URL",
      "A valid public http(s) article URL is required.",
    );
    return { done: true, result } as const;
  }

  if (before.reader.extracted.status === "ready" && before.reader.extracted.content) {
    return { done: true, result: { ok: true, status: "ready", article: before } as const } as const;
  }

  return { done: false, before, sourceUrl, urlKey: normalizeExtractionUrlKey(sourceUrl) } as const;
});

/** The embeddings Worker config for this extraction: the caller's, else the configured one. */
const embeddingConfigFor = (options: ExtractFullTextOptions) =>
  Effect.gen(function* () {
    const config = yield* AppConfig;
    return options.embeddingClassifier ?? embeddingClassifierConfig(EMBEDDING_TIMEOUT_MS, config);
  });

export const requestFullTextExtractionForUser = Effect.fn("extraction.request")(function* (
  userId: string,
  articleId: string,
  options: ExtractFullTextOptions = {},
) {
  const queue = yield* JobQueue;
  const log = yield* AppLogger;

  const prepared = yield* prepareExtraction(userId, articleId);
  if (prepared.done) {
    return prepared.result;
  }
  const { before, urlKey } = prepared;

  const cachedResult = yield* applyFreshExtractionCache(
    userId,
    before,
    yield* readFreshExtractionCache(urlKey),
    { ...options, embeddingClassifier: yield* embeddingConfigFor(options) },
  );
  if (cachedResult) {
    return cachedResult;
  }

  const queued = { ok: true, status: "queued", article: before } as const;
  if (before.reader.extracted.status === "pending" && before.reader.extracted.updatedAt) {
    return queued;
  }
  // Losing the claim means a concurrent request already queued this article's job.
  if (!(yield* claimPendingExtraction(before))) {
    return queued;
  }
  const article = yield* getArticleDetail(userId, articleId);

  const requestedAt = yield* DateTime.nowAsDate;
  const published = yield* queue
    .publish({
      type: "article.extract",
      payload: { articleId, userId, requestedAt: requestedAt.toISOString(), reason: "manual" },
    })
    .pipe(
      Effect.as(true),
      Effect.catchTag("RedisError", (error) =>
        log
          .error("articles.extract_full_text.enqueue_failed", {
            userId,
            articleId,
            error: serializeError(error),
          })
          .pipe(Effect.as(false)),
      ),
    );
  if (!published) {
    return yield* recordFailure(
      userId,
      before,
      "QUEUE_UNAVAILABLE",
      "Full text extraction could not be queued.",
    );
  }

  return { ok: true, status: "queued", article } as const;
});

/**
 * Worker-side source-page extraction. Persists to extracted* columns only; feed content fields stay unchanged.
 */
export const runArticleExtractionForUser = Effect.fn("extraction.run")(function* (
  userId: string,
  articleId: string,
  options: ExtractFullTextOptions = {},
) {
  const embeddingClassifier = yield* embeddingConfigFor(options);
  const prepared = yield* prepareExtraction(userId, articleId);
  if (prepared.done) {
    return prepared.result;
  }
  const { before, sourceUrl, urlKey } = prepared;

  const cachedResult = yield* applyFreshExtractionCache(
    userId,
    before,
    yield* readFreshExtractionCache(urlKey),
    { ...options, embeddingClassifier },
  );
  if (cachedResult) {
    return cachedResult;
  }

  /** Remember a failed extraction (so the next request skips the fetch) and answer with it. */
  const failExtraction = Effect.fn("extraction.failed")(function* (
    errorCode: string,
    rawMessage: string,
    finalUrl?: string,
  ) {
    const message = safeExtractErrorMessage(rawMessage);
    yield* upsertFailedExtractionCache({
      urlKey,
      sourceUrl: sourceUrl.href,
      finalUrl,
      errorCode,
      message,
    });
    return yield* recordFailure(userId, before, errorCode, message);
  });

  return yield* extractArticleContentFromUrl(before.link, {
    hostRateLimiter: options.hostRateLimiter,
  }).pipe(
    Effect.flatMap(
      Effect.fn("extraction.store")(function* (extracted) {
        const html = extracted.content.contentHtml?.trim();
        const text = extracted.content.contentText?.trim() ?? "";
        if (!html) {
          return yield* failExtraction(
            "NO_READABLE_CONTENT",
            "No readable article body was found.",
            extracted.finalUrl,
          );
        }

        const document = yield* compileExtractedDocument(
          extracted.rawHtml,
          extracted.finalUrl ?? sourceUrl.href,
          extracted.content.title,
        );
        yield* upsertReadyExtractionCache({
          urlKey,
          sourceUrl: sourceUrl.href,
          finalUrl: extracted.finalUrl,
          html,
          text,
          sanitizerVersion: extracted.sanitizerVersion,
          rawHtml: extracted.rawHtml,
          document,
        });
        yield* persistExtracted(
          before,
          {
            kind: "ready",
            html,
            text,
            sanitizerVersion: extracted.sanitizerVersion,
            raw: extracted.rawHtml,
            document,
            title: extracted.content.title,
          },
          options.titleReplacement,
        );
        if (before.articleType === "feed") {
          yield* reclassifyExtractedFeedItem(before, text, embeddingClassifier);
        }

        const article = yield* getArticleDetail(userId, articleId);
        return { ok: true, status: "ready", article } as const;
      }),
    ),
    Effect.catchTag("ExtractionFailed", (failure: ExtractionFailed) =>
      failExtraction(failure.errorCode, failure.errorMessage),
    ),
  );
});
