#!/usr/bin/env bun
// Builds packages/ingest/src/document/passes/math-macros.ts: the KaTeX built-in macros that
// MathJax (the native inline-formula renderer) does not know, each as a MathJax macro with the
// same body. The native SVG is only drawn for sources KaTeX accepted, so every gap here is a
// formula that renders on the web but would fall back to TeX source on iOS. A macro is emitted
// only when KaTeX accepts it and MathJax renders it correctly with the generated definition.
// Re-run after a KaTeX or MathJax upgrade:
//
//   bun scripts/katex/macros.ts
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { join } from "node:path";

const workerPackage = join(import.meta.dir, "../../packages/ingest/package.json");
const require = createRequire(workerPackage);
const katex = require("katex") as typeof import("katex");
require("katex/contrib/mhchem");
const { mathjax } = require("mathjax-full/js/mathjax.js");
const { TeX } = require("mathjax-full/js/input/tex.js");
const { AllPackages } = require("mathjax-full/js/input/tex/AllPackages.js");
const { SVG } = require("mathjax-full/js/output/svg.js");
const { liteAdaptor } = require("mathjax-full/js/adaptors/liteAdaptor.js");
const { RegisterHTMLHandler } = require("mathjax-full/js/handlers/html.js");

// Keep in step with MATHJAX_BLOCKED_PACKAGES in packages/ingest/src/document/passes/math.ts.
const BLOCKED = new Set([
  "html",
  "require",
  "href",
  "autoload",
  "bussproofs",
  "noerrors",
  "noundefined",
]);
const adaptor = liteAdaptor();
RegisterHTMLHandler(adaptor);
const output = new SVG({ fontCache: "none" });

type Macro = string | [string, number];

function mathjaxOk(tex: string, macros: Record<string, Macro>): boolean {
  try {
    const document = mathjax.document("", {
      InputJax: new TeX({
        packages: AllPackages.filter((name: string) => !BLOCKED.has(name)),
        macros,
        formatError: (_jax: unknown, error: Error) => {
          throw error;
        },
      }),
      OutputJax: output,
    });
    const html = adaptor.outerHTML(document.convert(tex, { display: false })) as string;
    return !html.includes("merror") && !html.includes("<text");
  } catch {
    return false;
  }
}

function katexOk(tex: string): boolean {
  try {
    katex.renderToString(tex, { throwOnError: true, strict: "ignore", trust: false });
    return true;
  } catch {
    return false;
  }
}

const source = readFileSync(require.resolve("katex/dist/katex.mjs"), "utf8");
const found: Record<string, Macro> = {};
const definition = /defineMacro\("((?:\\\\[A-Za-z]+))", *"((?:[^"\\]|\\.)*)"\)/g;
for (const match of source.matchAll(definition)) {
  const name = (new Function(`return "${match[1]}"`)() as string).slice(1);
  const raw = new Function(`return "${match[2]}"`)() as string;
  // `##` is a literal `#` (hex colours); only a lone `#n` is an argument.
  const body = raw.replaceAll("##", "#");
  // Bodies that lean on KaTeX internals cannot be restated in MathJax.
  if (
    /\\@|\\html@|\\TextOrMath|\\ifmmode|\\nobreak|\\expandafter|\\gdef|\\global|\\edef|\\let|\\relax|\\mathchoice|\\char|\\kern|\\DOTSB|\\mathrel\{\\sim\\mathrel/.test(
      body,
    )
  ) {
    continue;
  }
  const args = Math.max(
    0,
    ...[...raw.replaceAll("##", "").matchAll(/#(\d)/g)].map((arg) => Number(arg[1])),
  );
  const use = `\\${name}${"{x}".repeat(args)}`;
  if (!katexOk(use) || mathjaxOk(use, {})) {
    continue;
  }
  const macro: Macro = args > 0 ? [body, args] : body;
  if (mathjaxOk(use, { [name]: macro })) {
    found[name] = macro;
  }
}
// KaTeX's `\argmax` carries a `\DOTSB` hint MathJax does not have; the visible body is the same.
for (const name of ["argmax", "argmin"]) {
  const macro = `\\operatorname*{arg\\,${name.slice(3)}}`;
  if (katexOk(`\\${name}_x f`) && mathjaxOk(`\\${name}_x f`, { [name]: macro })) {
    found[name] = macro;
  }
}

const entries = Object.entries(found).sort(([a], [b]) => a.localeCompare(b));
const lines = entries.map(([name, macro]) => `  ${name}: ${JSON.stringify(macro)},`);
const target = join(import.meta.dir, "../../packages/ingest/src/document/passes/math-macros.ts");
writeFileSync(
  target,
  `// Generated by scripts/katex/macros.ts; do not edit by hand.
/** KaTeX built-in macros MathJax lacks, restated so native inline math accepts what the web does. */
export const KATEX_MACROS_FOR_MATHJAX: Record<string, string | [string, number]> = {
${lines.join("\n")}
};
`,
);
console.log(`${entries.length} macros -> ${target}`);
